export const getAssetById = (id: string): MediaAsset | undefined => {
  return MEDIA_ASSETS.find((a) => a.id === id);
};

export const getAssetsByCategory = (category: string): MediaAsset[] => {
  if (category === 'ALL') return MEDIA_ASSETS.filter((a) => a.type !== 'audio');
  if (category === 'VIDEOS') return MEDIA_ASSETS.filter((a) => a.type === 'video');
  return MEDIA_ASSETS.filter((a) => a.category === category && a.type !== 'audio');
};
